import { forwardRef } from 'react';
import { TrendingUp, TrendingDown, Quote, ListChecks, XCircle } from 'lucide-react';
import { DailyBars } from './Charts.jsx';
import Meter from './Meter.jsx';

const ReportCard = forwardRef(function ReportCard({ report, detailed = false }, ref) {
  const r = report;
  const maxEx = Math.max(...r.excuses.map((e) => e.count));
  return (
    <article className="report-card tactile-card" ref={ref} aria-label={`Reality Report ${r.week}`}>
      <header className="rc-head">
        <div><span className="eyebrow dark">REALITY REPORT · {r.label.toUpperCase()}</span><h3 className="rc-week">{r.week}</h3></div>
        <div className="rc-score" aria-label={`Consistency score ${r.score} percent`}>
          <div className="num3d">{r.score}<small>%</small></div><span>CONSISTENCY</span>
        </div>
      </header>

      <div className="rc-stats">
        <div className="tactile-card flat"><small>COMMITTED</small><b className="num3d">{r.committed}</b></div>
        <div className="tactile-card flat accent"><small>COMPLETED</small><b className="num3d">{r.completed}</b></div>
        <div className="tactile-card flat danger"><small>MISSED</small><b className="num3d">{r.missed}</b></div>
      </div>

      <div className="rc-grid">
        <section>
          <h4 className="rc-h">Daily completion</h4>
          <DailyBars data={r.daily} height={200} />
          <div className="rc-bw">
            <div><TrendingUp size={16} color="#111318" /><span><small>STRONGEST DAY</small><b>{r.best.day} · {r.best.pct}%</b></span></div>
            <div><TrendingDown size={16} color="#E52929" /><span><small>WEAKEST DAY</small><b>{r.worst.day} · {r.worst.pct}%</b></span></div>
          </div>
        </section>
        <section>
          <h4 className="rc-h">Excuse patterns</h4>
          <div className="excuse-list">
            {r.excuses.map((e) => (
              <div key={e.label} className="excuse-row"><span>“{e.label}”</span><Meter value={(e.count / maxEx) * 100} tone={e.count === maxEx ? 'red' : ''} label={e.label} /><b>×{e.count}</b></div>
            ))}
          </div>
        </section>
      </div>

      <section className="rc-ai">
        <Quote size={22} /><p>{r.analysis}</p>
      </section>

      {detailed && (
        <section>
          <h4 className="rc-h"><XCircle size={16} /> Missed commitments</h4>
          <ul className="rc-missed">{r.missedList.map((m) => <li key={m}>{m}</li>)}</ul>
        </section>
      )}

      <section>
        <h4 className="rc-h"><ListChecks size={16} /> Next week&apos;s action plan</h4>
        <ol className="rc-plan">{r.actions.map((a, i) => (<li key={a}><b className="num3d">{i + 1}</b><span>{a}</span></li>))}</ol>
      </section>
      <footer className="rc-foot">Generated by Brutality AI · Reality Agent · demo data</footer>
    </article>
  );
});
export default ReportCard;
